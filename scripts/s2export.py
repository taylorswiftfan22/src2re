FLAGS = ida_name.SN_NOWARN | ida_name.SN_NOCHECK | ida_name.SN_FORCE
done = 0
for rva, name, is_func, cmt in SYMS:
    ea = BASE + rva
    if is_func and not ida_funcs.get_func(ea):
        ida_funcs.add_func(ea)
    if ida_name.set_name(ea, name, FLAGS):
        done += 1
    if cmt:
        ida_bytes.set_cmt(ea, cmt, True)
print("source2-re: named %d of %d" % (done, len(SYMS)))
